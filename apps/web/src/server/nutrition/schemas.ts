import { z } from 'zod';
import { FoodSeed, IsoDate, IsoDateTime, LocalizedText, Macros, NutritionDocument, NutritionTargets } from '@dawlyy/core/types';

const text = z.string().trim().min(1).max(200);
const tags = z.array(text).max(50);
const note = z.string().trim().max(4000);
/** Task 6: drafts permit an empty meal list; publication uses the unmodified core schema. */
export const draftDocumentSchema = NutritionDocument.extend({ meals: z.array(NutritionDocument.shape.meals.element).max(50) }).superRefine((doc, ctx) => {
  const ids = new Set<string>();
  const visit = (id: string) => { if (ids.has(id)) ctx.addIssue({ code: 'custom', message: 'duplicate_id' }); ids.add(id); };
  for (const meal of doc.meals) {
    visit(meal.id);
    for (const option of meal.options) {
      visit(option.id);
      for (const item of option.items) {
        visit(item.id);
        if (item.measure.kind === 'custom' && !item.measure.label) ctx.addIssue({ code: 'custom', message: 'custom_label_required' });
      }
    }
  }
  for (const supplement of doc.supplements) {
    visit(supplement.id);
    if (supplement.mealId && !doc.meals.some(meal => meal.id === supplement.mealId)) ctx.addIssue({ code: 'custom', message: 'supplement_meal_unknown' });
  }
});
/** Task 6: coach inputs exclude identity, tenant, author and version pointers. */
export const createPlanSchema = z.object({ name: LocalizedText, tags: tags.optional(), targets: NutritionTargets.optional() }).strict();
/** Task 6: sparse metadata edit, with server-generated archive timestamp. */
export const patchPlanSchema = z.object({ name: LocalizedText.optional(), tags: tags.optional(), archived: z.boolean().optional() }).strict().refine(value => Object.keys(value).length > 0);
/** Task 6: whole-document optimistic replacement, including optional same-version revision token. */
export const draftSchema = z.object({ document: draftDocumentSchema, baseVersionNo: z.number().int().positive().max(2147483647), baseRevision: z.string().regex(/^[a-f0-9]{64}$/).optional(), changeNote: note.optional() }).strict();
/** Task 6: publication freshness preconditions and note. */
export const publishSchema = z.object({ changeNote: note.optional(), baseVersionNo: z.number().int().positive().optional(), baseRevision: z.string().regex(/^[a-f0-9]{64}$/).optional() }).strict();
/** Task 6: historic snapshots are reverted by creating a new draft. */
export const revertSchema = z.object({ toVersionNo: z.number().int().positive(), changeNote: note.optional() }).strict();
/** Task 6: explicit replacement and optional subscription binding. */
export const assignSchema = z.object({ clientId: z.uuid(), subscriptionId: z.uuid().optional(), startDate: IsoDate.optional(), publish: z.boolean().default(false), replace: z.boolean().default(false) }).strict();
/** Task 6: list filters retain raw cursor/limit for the shared parser. */
export const planListSchema = z.object({ kind: z.enum(['template', 'client']).optional(), clientId: z.uuid().optional(), q: z.string().max(200).optional(), archived: z.enum(['true', 'false']).optional(), limit: z.string().optional(), cursor: z.string().optional() });
/** Task 6: foods may be searched by folded names and aliases. */
export const foodListSchema = z.object({ q: z.string().max(200).optional(), category: z.string().max(100).optional(), source: z.enum(['db', 'label', 'estimate', 'coach']).optional(), includeHidden: z.enum(['true', 'false']).optional(), limit: z.string().optional(), cursor: z.string().optional() });
const foodFields = FoodSeed.omit({ slug: true, source: true }).extend({ name: LocalizedText, aliases: z.array(text).max(100).default([]), category: text, measures: FoodSeed.shape.measures.unwrap().max(50).default([]) });
/** Task 6: source and slug are generated by the service. */
export const foodInput = foodFields.strict();
/** Task 6: partial food edits preserve omitted defaults. */
export const foodPatch = foodFields.extend({ aliases: z.array(text).max(100), measures: FoodSeed.shape.measures.unwrap().max(50), tags }).partial().strict().refine(value => Object.keys(value).length > 0);
/** Task 6: client-authored meal data; no author/client/version stamps are accepted. */
export const mealLogSchema = z.object({ clientUuid: z.uuid(), localDate: IsoDate, mealId: z.string().min(1).max(64).optional(), optionId: z.string().min(1).max(64).optional(), status: z.enum(['eaten', 'skipped', 'partial']), freeEntry: z.object({ text: z.string().trim().min(1).max(4000), macros: Macros.optional() }).strict().optional(), note: note.optional(), clientUpdatedAt: IsoDateTime }).strict().refine(value => !!value.mealId || !!value.freeEntry, 'meal_or_entry_required');
/** Task 6: supplement sync uses the same monotonic timestamp rule as meal logs. */
export const supplementLogSchema = z.object({ clientUuid: z.uuid(), supplementId: z.string().min(1).max(64), localDate: IsoDate, taken: z.boolean(), clientUpdatedAt: IsoDateTime }).strict();
/** Task 6: append-only hydration, measured in millilitres. */
export const waterSchema = z.object({ clientUuid: z.uuid(), amountMl: z.number().positive().max(10000), localDate: IsoDate }).strict();
/** Task 6: date-scoped log history with optional coach client selector. */
export const logListSchema = z.object({ date: IsoDate, clientId: z.uuid().optional(), limit: z.string().optional(), cursor: z.string().optional() });
