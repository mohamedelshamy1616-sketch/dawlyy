import { z } from '@hono/zod-openapi';
import { BlockKind, Id, IsoDate, LocalizedText, PlannedSet, ProgramDocument, ProgressionRule, WorkoutBlock } from '@dawlyy/core/types';
import type { ProgramOp } from '@dawlyy/core/program-edit';

const uuid = z.string().uuid();
const text = LocalizedText;
const positive = z.number().int().min(1).max(104);
const note = z.string().trim().max(2000);
const patchSet = PlannedSet.omit({ setNo: true }).partial().strict();
const op = <T extends string, S extends z.ZodRawShape>(type: T, shape: S) => z.object({ type: z.literal(type), ...shape }).strict();
const phase = { phaseId: Id };
const week = { ...phase, weekId: Id };
const day = { dayId: Id };
const block = { ...day, blockId: Id };
const item = { ...day, itemId: Id };
const toIndex = z.number().int();

/** Task 4: wire validation for every core edit operation; structural fields have dedicated operations. */
export const programOpSchema: z.ZodType<ProgramOp> = z.discriminatedUnion('type', [
  op('phase.add', { afterPhaseId: Id.optional(), name: text.optional(), weeks: positive.optional() }),
  op('phase.update', { ...phase, patch: z.object({ name: text.optional(), goal: text.nullable().optional() }).strict() }),
  op('phase.remove', phase), op('phase.move', { ...phase, toIndex }), op('phase.duplicate', phase),
  op('week.add', { ...phase, afterWeekId: Id.optional(), copyFromWeekId: Id.optional() }),
  op('week.remove', week), op('week.duplicate', week), op('week.move', { ...week, toIndex }),
  op('week.update', { ...week, patch: z.object({ isDeload: z.boolean().optional(), note: text.nullable().optional() }).strict() }),
  op('day.setKind', { ...day, kind: z.enum(['training', 'rest', 'active_recovery']) }),
  op('day.update', { ...day, patch: z.object({ note: text.nullable().optional() }).strict() }),
  op('day.copyTo', { fromDayId: Id, toDayIds: z.array(Id).max(728) }),
  op('day.swap', { dayIdA: Id, dayIdB: Id }), op('day.clear', day),
  op('workout.update', { ...day, patch: z.object({ name: text.optional(), estimatedMinutes: z.number().int().positive().nullable().optional(), note: text.nullable().optional() }).strict() }),
  op('block.add', { ...day, kind: BlockKind, afterBlockId: Id.optional(), name: text.optional() }),
  op('block.update', { ...block, patch: z.object({ kind: BlockKind.optional(), name: text.nullable().optional(), rounds: z.number().int().positive().nullable().optional(), restBetweenRoundsSec: z.number().int().nonnegative().nullable().optional(), note: text.nullable().optional() }).strict() }),
  op('block.remove', block), op('block.move', { ...block, toIndex }),
  op('block.insert', { ...day, block: WorkoutBlock, afterBlockId: Id.optional() }),
  op('item.add', { ...block, exerciseId: uuid, sets: z.number().int().min(1).max(100).optional(), template: patchSet.optional() }),
  op('item.update', { ...item, patch: z.object({ progressionRule: ProgressionRule.nullable().optional(), coachNote: text.nullable().optional(), alternatives: z.array(uuid).max(100).nullable().optional() }).strict() }),
  op('item.replaceExercise', { ...item, exerciseId: uuid }), op('item.remove', item),
  op('item.move', { ...item, toBlockId: Id, toIndex }), op('item.duplicate', item),
  op('set.add', { ...item, copyLast: z.boolean().optional() }),
  op('set.update', { ...item, setNo: z.number().int().positive(), patch: patchSet }),
  op('set.remove', { ...item, setNo: z.number().int().positive() }),
  op('set.applyToAll', { ...item, patch: patchSet }),
  op('meta.update', { patch: z.object({ startDate: IsoDate.nullable().optional(), endDate: IsoDate.nullable().optional(), reviewDate: IsoDate.nullable().optional(), goal: text.nullable().optional(), notes: text.nullable().optional() }).strict() }),
]);

/** Task 4: templates and copies use stable descending updated-time pagination. */
export const programListSchema = z.object({
  kind: z.enum(['template', 'client']).optional(), clientId: uuid.optional(), q: z.string().trim().max(200).optional(),
  archived: z.enum(['true', 'false']).optional(), limit: z.string().optional(), cursor: z.string().optional(),
}).strict();
/** Task 4: template creation accepts only coach-owned fields. */
export const createProgramSchema = z.object({ name: LocalizedText, tags: z.array(z.string().trim().min(1).max(80)).max(50).optional(), weeks: positive.optional(), trainingDays: z.array(z.number().int().min(0).max(6)).max(7).optional() }).strict();
/** Task 4: sparse head edits; archivedAt is generated by the service, never accepted as a stamp. */
export const patchProgramSchema = z.object({ name: LocalizedText.optional(), tags: createProgramSchema.shape.tags, archived: z.boolean().optional() }).strict().refine(value => Object.keys(value).length > 0);
const base = { baseVersionNo: z.number().int().positive().max(2147483647), baseRevision: z.string().regex(/^[a-f0-9]{64}$/).optional() };
/** Task 4: full draft replacement with optional stronger same-version concurrency detection. */
export const draftSchema = z.object({ ...base, document: ProgramDocument, changeNote: note.optional() }).strict();
/** Task 4: generated JSON element ids keep optimistic client operations identical to server operations. */
export const opsSchema = z.object({ ...base, ops: z.array(programOpSchema).min(1).max(100), editIds: z.array(uuid).max(20000).optional() }).strict();
/** Task 4: publication note and optional freshness preconditions. */
export const publishSchema = z.object({ changeNote: note.optional(), baseVersionNo: base.baseVersionNo.optional(), baseRevision: base.baseRevision }).strict();
/** Task 4: reverting creates a fresh draft instead of rewriting history. */
export const revertSchema = z.object({ toVersionNo: z.number().int().positive().max(2147483647), changeNote: note.optional() }).strict();
/** Task 4: replacement must be explicit; subscription ownership is resolved through RLS. */
export const assignSchema = z.object({ clientId: uuid, subscriptionId: uuid.optional(), startDate: IsoDate.optional(), publish: z.boolean().default(false), replace: z.boolean().default(false) }).strict();
