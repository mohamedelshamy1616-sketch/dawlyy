import { sql } from 'drizzle-orm';
import { date, foreignKey, index, jsonb, pgTable, text, timestamp, uniqueIndex, uuid } from 'drizzle-orm/pg-core';
import { ACCESS, CAN_CREATE_CLIENTS, ME, OWN, OWNER, STAFF, T, allow, tenantGuard } from './_rls';
import { clientStatus } from './enums';
import { tenants } from './tenants';

// 0004 hand edit H2: place referenced unique indexes before foreign keys, doc §11.2.

/** Spec §10 (client management), §11 (Client 360). */

export type ClientProfile = {
  sex?: 'male' | 'female';
  heightCm?: number;
  goal?: string;
  trainingLevel?: 'beginner' | 'intermediate' | 'advanced';
  injuries?: string[];
  allergies?: string[];
  dislikes?: string[];
  schedule?: { trainingDays?: number[]; preferredTime?: string };
  equipment?: string[];
  units?: { weight: 'kg' | 'lb'; length: 'cm' | 'in' };
  [key: string]: unknown;
};

/** doc §5.2, §8: clients policies and referential integrity. */
// triggers, functions and grants: 0006, doc §6.3, §7, §11.4.
export const clients = pgTable(
  'clients',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    /** Persistent human-readable id, e.g. DW-000123. Generated by app.next_client_code(). */
    code: text('code').notNull().default(''),
    searchKey: text('search_key').notNull().default(''),
    /** Linked once the client accepts an invitation. */
    membershipId: uuid('membership_id'),
    firstName: text('first_name').notNull(),
    lastName: text('last_name'),
    displayName: text('display_name'),
    email: text('email'),
    phone: text('phone'),
    whatsapp: text('whatsapp'),
    birthDate: date('birth_date'),
    locale: text('locale').notNull().default('ar'),
    timezone: text('timezone').notNull().default('Africa/Cairo'),
    status: clientStatus('status').notNull().default('lead'),
    tags: text('tags').array().notNull().default([]),
    profile: jsonb('profile').$type<ClientProfile>().notNull().default({}),
    source: text('source'),
    /** Day 0 of the current engagement (spec §22); subscriptions carry their own dates too. */
    startedOn: date('started_on'),
    createdBy: uuid('created_by'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }),
    archivedAt: timestamp('archived_at', { withTimezone: true }),
    archivedBy: uuid('archived_by'),
  },
  (t) => [
    uniqueIndex('clients_tenant_code_uq').on(t.tenantId, t.code),
    index('clients_tenant_status_idx').on(t.tenantId, t.status),
    index('clients_tenant_phone_idx').on(t.tenantId, t.phone),
    index('clients_membership_idx').on(t.membershipId),
    uniqueIndex('clients_tenant_id_uq').on(t.tenantId, t.id),
    index('clients_tenant_search_idx').on(t.tenantId, t.searchKey),
    ...tenantGuard('clients', T(t.tenantId)),
    ...allow('clients_staff', ['select', 'update'], sql`${T(t.tenantId)} and ${STAFF} and ${ACCESS(t.id)}`),
    ...allow('clients_create', ['insert'], sql`${T(t.tenantId)} and ${STAFF} and ${CAN_CREATE_CLIENTS}`),
    ...allow('clients_client', ['select', 'update'], sql`${T(t.tenantId)} and ${OWN(t.id)}`),
  ],
).enableRLS();

/** Private coach notes: never visible to the client (spec §11, §61). */
/** doc §5.2, §8: client_notes policies and referential integrity. */
// triggers, functions and grants: 0006, doc §6.3, §7, §11.4.
export const clientNotes = pgTable(
  'client_notes',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    clientId: uuid('client_id').notNull(),
    body: text('body').notNull(),
    pinned: timestamp('pinned_at', { withTimezone: true }),
    authorUserId: uuid('author_user_id').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }),
  },
  (t) => [
    index('client_notes_tenant_client_idx').on(t.tenantId, t.clientId),
    foreignKey({
      name: 'client_notes_client_fk',
      columns: [t.tenantId, t.clientId],
      foreignColumns: [clients.tenantId, clients.id],
    }).onDelete('cascade'),
    ...tenantGuard('client_notes', T(t.tenantId)),
    ...allow('client_notes_staff', ['select', 'insert'], sql`${T(t.tenantId)} and ${STAFF} and ${ACCESS(t.clientId)}`),
    ...allow('client_notes_author', ['update', 'delete'], sql`${T(t.tenantId)} and ${STAFF} and ${ACCESS(t.clientId)} and (${ME(t.authorUserId)} or ${OWNER})`),
  ],
).enableRLS();

/** Risk and attention flags computed by rules or set by the coach (spec §11 dashboard "who needs attention"). */
/** doc §5.2, §8: client_flags policies and referential integrity. */
// triggers, functions and grants: 0006, doc §6.3, §7, §11.4.
export const clientFlags = pgTable(
  'client_flags',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    tenantId: uuid('tenant_id')
      .notNull()
      .references(() => tenants.id, { onDelete: 'cascade' }),
    clientId: uuid('client_id').notNull(),
    /** e.g. missed_checkins, adherence_drop, expiring_soon, pending_payment, no_data_7d */
    kind: text('kind').notNull(),
    severity: text('severity').notNull().default('normal'),
    detail: jsonb('detail').$type<Record<string, unknown>>(),
    raisedAt: timestamp('raised_at', { withTimezone: true }).notNull().defaultNow(),
    resolvedAt: timestamp('resolved_at', { withTimezone: true }),
    resolvedBy: uuid('resolved_by'),
  },
  (t) => [
    index('client_flags_tenant_open_idx').on(t.tenantId, t.resolvedAt),
    index('client_flags_client_idx').on(t.clientId),
    foreignKey({
      name: 'client_flags_client_fk',
      columns: [t.tenantId, t.clientId],
      foreignColumns: [clients.tenantId, clients.id],
    }).onDelete('cascade'),
    ...tenantGuard('client_flags', T(t.tenantId)),
    ...allow('client_flags_staff', ['select', 'insert', 'update'], sql`${T(t.tenantId)} and ${STAFF} and ${ACCESS(t.clientId)}`),
  ],
).enableRLS();
